// backtest-vault-writer.js -- persists recurring backtest results into the
// real Obsidian vault, mirroring vault-research-writer.js's existing
// pattern exactly (dated note, idempotent published-ledger, explicit
// lower-rigor Provenance section). Added 2026-09-13 alongside
// generate-backtest-tasks.js and backtest-supervisor.js to close the
// "no recurring backtest" gap named in ARCHITECTURE.md section 9.
//
// Report-only, same as its caller: this module only ever writes a vault
// note and appends to its own ledger. It never touches paper-trades.jsonl
// or calls execute-portfolio-setup.js.

const avPaths = require('../lib/paths.js');
const fs = require('fs');
const path = require('path');
const runTask = require('../platform/run-task.js');

const VAULT_ROOT = avPaths.ROOT;
const PUBLISHED_LEDGER_PATH = path.join(VAULT_ROOT, 'bus', 'backtest-vault-published.jsonl');

const RESEARCH_CATEGORY_ROOT = path.join(VAULT_ROOT, '06 - Markets & Trading Research');
const BACKTEST_DIR = path.join(RESEARCH_CATEGORY_ROOT, '04 - Strategy Backtests');
const DAILY_DIR = path.join(BACKTEST_DIR, 'Daily Score-Ranking');
const WEEKLY_DIR = path.join(BACKTEST_DIR, 'Weekly Entry-Exit Validation');
const WEIGHT_SEARCH_DIR = path.join(BACKTEST_DIR, 'Weight Search History');
const BIDAILY_AUDIT_DIR = path.join(BACKTEST_DIR, 'Bi-Daily Audits');

function todayIso() {
  return new Date().toISOString().slice(0, 10);
}

function ensureDir(dir) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function readPublishedLedger() {
  if (!fs.existsSync(PUBLISHED_LEDGER_PATH)) return new Set();
  return new Set(
    fs.readFileSync(PUBLISHED_LEDGER_PATH, 'utf8').split('\n').filter((l) => l.trim())
      .map((l) => { try { return JSON.parse(l).ledgerId; } catch (_) { return null; } })
      .filter(Boolean)
  );
}

function markPublished(ledgerId, notePath) {
  ensureDir(path.dirname(PUBLISHED_LEDGER_PATH));
  fs.appendFileSync(PUBLISHED_LEDGER_PATH, JSON.stringify({ ledgerId, notePath, ts: new Date().toISOString() }) + '\n', 'utf8');
}

function noteFrontmatter(type, asOf, extra) {
  return [
    '---',
    'tier: warm',
    'relevance: 0.6',
    `last_accessed: ${asOf}`,
    `type: ${type}`,
    `as_of: ${asOf}`,
    'status: auto-published',
    ...extra,
    '---',
  ].join('\n');
}

// One note per daily backtest-screen-score-v2.js run. `verdictLine` is the
// script's own top-line verdict (parsed by backtest-supervisor.js from its
// results markdown -- never re-derived or paraphrased here); `resultsPath`
// is the absolute path to that run's own results file, quoted verbatim,
// not summarized further.
function publishDailyBacktestNote({ asOfDate, verdictLine, resultsPath, resultsExcerpt }) {
  const ledgerId = `daily:${asOfDate}`;
  const published = readPublishedLedger();
  if (published.has(ledgerId)) {
    return { written: false, reason: `already published for ${asOfDate} (see ${path.basename(PUBLISHED_LEDGER_PATH)})` };
  }

  ensureDir(DAILY_DIR);
  const noteFileName = `${asOfDate} Screen-Score Backtest.md`;
  const notePath = path.join(DAILY_DIR, noteFileName);
  const relResultsPath = path.relative(VAULT_ROOT, resultsPath);

  const body = [
    noteFrontmatter('backtest_snapshot', asOfDate, [
      'tags: ["markets", "backtest", "automated"]',
    ]),
    `# Daily Screen-Score Backtest — ${asOfDate}`,
    '',
    'Automated, unattended re-run of the live screen-score ranking backtest -- see [[Research Standards & Source Tiers]] for this vault\'s rigor-tiering convention. This note reports what the script found; it does not itself recommend any trading action, and nothing downstream of it executes an order.',
    '',
    '## Verdict',
    '',
    verdictLine || '(no top-line verdict line was found in this run\'s results file -- see the full report for detail.)',
    '',
    '## Excerpt',
    '',
    resultsExcerpt || '(full report not excerpted this run; see the source file below.)',
    '',
    '## Provenance',
    '',
    `Generated by \`bus/fleet/backtest-screen-score-v2.js\`, scheduled daily by \`bus/fleet/backtest-supervisor.js\` (added 2026-09-13). Full report: \`${relResultsPath}\`. Report-only -- does not affect live \`execute-portfolio-setup.js --auto\` execution.`,
  ].join('\n');

  fs.writeFileSync(notePath, body, 'utf8');
  markPublished(ledgerId, notePath);
  return { written: true, path: notePath };
}

// One note per weekly deep multi-agent batch, read directly from the
// batch-level synthesis task's own output (must be status:done) -- same
// "never fabricate, refuse with a stated reason" discipline as
// vault-research-writer.js's publishCompanyResearch().
function publishWeeklyBacktestNote(pilot, weekPrefix, batchTaskId) {
  const ledgerId = batchTaskId;
  const published = readPublishedLedger();
  if (published.has(ledgerId)) {
    return { written: false, reason: `already published (see ${path.basename(PUBLISHED_LEDGER_PATH)})` };
  }

  const task = runTask.readTaskFile(batchTaskId);
  if (!task) return { written: false, reason: `task file not found: ${batchTaskId}` };
  if (task.status !== 'done') return { written: false, reason: `task status is "${task.status}", not "done" -- nothing to publish yet` };
  if (!task.output || !task.output.trim()) return { written: false, reason: 'task is done but has no parseable output -- refusing to publish an empty note' };

  const asOf = todayIso();
  ensureDir(WEEKLY_DIR);
  const noteFileName = `${weekPrefix} ${pilot} Entry-Exit Validation.md`;
  const notePath = path.join(WEEKLY_DIR, noteFileName);

  const body = [
    noteFrontmatter('backtest_snapshot', asOf, [
      `pilot: ${pilot}`,
      `week: ${weekPrefix}`,
      'tags: ["markets", "backtest", "automated", "multi-agent"]',
    ]),
    `# Weekly Entry/Exit Validation — ${pilot} — ${weekPrefix}`,
    '',
    'Two INDEPENDENT specialists (Codex and a separate headless Claude instance) each backtested the live strategy\'s entry/exit rule against real historical data for this week\'s rotating symbol sample, reconciled per-symbol, then combined into the batch verdict below. See [[Research Standards & Source Tiers]] for this vault\'s rigor-tiering convention. Report-only: this note and the pipeline that produced it never place or size any order.',
    '',
    '## Batch verdict',
    '',
    task.output.trim(),
    '',
    '## Provenance',
    '',
    `Generated by the weekly rotation in \`bus/fleet/backtest-supervisor.js\`, task suite authored by \`bus/fleet/generate-backtest-tasks.js\` (added 2026-09-13). Batch synthesis task: \`${batchTaskId}\`. Dispatched by the standing \`agentvault-queue-daemon\` service like any other task file. Report-only -- does not affect live \`execute-portfolio-setup.js --auto\` execution.`,
  ].join('\n');

  fs.writeFileSync(notePath, body, 'utf8');
  markPublished(ledgerId, notePath);
  return { written: true, path: notePath };
}

function fmtPct(v) {
  return `${v >= 0 ? '+' : ''}${(v * 100).toFixed(2)}%`;
}

function gridTableMarkdown(grid) {
  const header = '| Rank | chgPct weight | avgVolume weight | Train worst-horizon excess vs benchmark |\n|---:|---:|---:|---:|';
  const rows = grid.map((row, i) => `| ${i + 1} | ${row.weights.chgPct} | ${row.weights.avgVolume} | ${fmtPct(row.objective)} |`);
  return `${header}\n${rows.join('\n')}`;
}

function testResultTableMarkdown(testResult) {
  const header = '| Horizon | Trials | vs universe (95% CI) | vs benchmark (95% CI) |\n|---:|---:|---|---|';
  const rows = testResult.nonOverlappingMetrics.map((m) => `| ${m.horizon}d | ${m.trialCount} | ${fmtPct(m.netVsUniverse.mean)} (${fmtPct(m.netVsUniverse.ciLow)} to ${fmtPct(m.netVsUniverse.ciHigh)}) | ${fmtPct(m.netVsBenchmark.mean)} (${fmtPct(m.netVsBenchmark.ciLow)} to ${fmtPct(m.netVsBenchmark.ciHigh)}) |`);
  return `${header}\n${rows.join('\n')}`;
}

// One note per weekly parameter-search run (applied or declined -- an
// honest null result is published exactly like a positive one). Unlike
// this file's other publish functions, this one's CALLER
// (backtest-parameter-search.js) can change live trading behavior
// (screen-score-weights.json) -- this function itself still only ever
// writes a vault note and its own ledger, same as everywhere else here.
function publishWeightSearchNote(pilot, weekPrefix, result) {
  const ledgerId = `weightsearch:${pilot}:${weekPrefix}`;
  const published = readPublishedLedger();
  if (published.has(ledgerId)) {
    return { written: false, reason: `already published for ${pilot} week ${weekPrefix} (see ${path.basename(PUBLISHED_LEDGER_PATH)})` };
  }

  const asOf = todayIso();
  ensureDir(WEIGHT_SEARCH_DIR);
  const noteFileName = `${weekPrefix} ${pilot} Weight Search.md`;
  const notePath = path.join(WEIGHT_SEARCH_DIR, noteFileName);
  const growthLine = result.previousTestCount !== null
    ? `Test set grew from ${result.previousTestCount} to ${result.testCount} signals since the last run.`
    : `First run under the fixed-split design -- this split date is now permanent for ${pilot}; the test set will only ever grow from here.`;

  const body = [
    noteFrontmatter('backtest_snapshot', asOf, [
      `pilot: ${pilot}`,
      `run_date: ${weekPrefix}`,
      `split_date: ${result.splitDate}`,
      `applied: ${result.applied}`,
      'tags: ["markets", "backtest", "automated", "parameter-search"]',
    ]),
    `# Weight Search — ${pilot} — ${weekPrefix}`,
    '',
    `A grid search over computeScreenScore()'s chgPct/avgVolume weight split (marketCap fixed at 0 -- deferred dimension, see ARCHITECTURE.md section 13), fit on a FIXED chronological TRAIN slice (never re-split -- see ARCHITECTURE.md section 17) and re-verified on a held-out TEST slice that only ever grows forward in place, using the exact same predeclared, non-overlapping, cost-adjusted, dual-comparator bar the live daily verdict already uses. See [[Research Standards & Source Tiers]]. This is the "learning" layer: a real deterministic parameter fit against data, not an LLM judgment.`,
    '',
    `Train/test boundary fixed at **${result.splitDate}** for ${pilot} -- everything before this date is TRAIN (never moves), everything after is TEST (grows every run). ${growthLine} Runs roughly every 3 days; a horizon still needs real calendar time >= its own length (5/10/20 days) to gain one new non-overlapping data point, so most runs mainly add fresh 5-day-horizon evidence -- expected, not a shortfall.`,
    '',
    '## Outcome',
    '',
    result.applied
      ? `**APPLIED.** Live weights for \`${pilot}\` changed from \`${JSON.stringify(result.previousWeights)}\` to \`${JSON.stringify({ chgPct: result.winner.weights.chgPct, avgVolume: result.winner.weights.avgVolume, marketCap: result.winner.weights.marketCap })}\` -- the winning combination cleared the out-of-sample bar on ${result.testCount} held-out signals.`
      : `**No change applied.** The best in-sample combination (chgPct=${result.winner.weights.chgPct}, avgVolume=${result.winner.weights.avgVolume}) did NOT clear the out-of-sample bar on ${result.testCount} held-out signals. Live weights remain \`${JSON.stringify(result.previousWeights)}\`. This is an honest null result, not a failure -- most runs are expected to look like this given the formula's own separately-confirmed lack of edge.`,
    '',
    `## Grid search (train, ${result.trainCount} signals, fixed since ${result.splitDate})`,
    '',
    gridTableMarkdown(result.grid.slice(0, 5)),
    '',
    `Full grid: ${result.grid.length} combinations tested (chgPct 0-100 in steps of 10, avgVolume = 100 - chgPct). Objective: worst-of-three-horizons mean cost-adjusted excess return vs. benchmark (conservative -- avoids picking a combination that only looks good on one horizon).`,
    '',
    `## Out-of-sample verification (test, ${result.testCount} signals, extending since ${result.splitDate})`,
    '',
    testResultTableMarkdown(result.testResult),
    '',
    `Pass rule (unchanged from the existing daily verdict): all three horizons' cost-adjusted, non-overlapping, paired 95% confidence intervals entirely above zero vs. both the full universe and the benchmark. Result: **${result.passes ? 'PASSED' : 'did not pass'}**.`,
    '',
    '## Provenance',
    '',
    `Generated by \`bus/fleet/backtest-parameter-search.js\` (added 2026-09-13, fixed-split redesign 2026-09-14), scheduled every ~3 days by \`bus/fleet/backtest-supervisor.js\`. Live weights live in \`bus/fleet/data/screen-score-weights.json\`, git-tracked -- its history is the full audit trail of every real formula change. Split-date state: \`bus/fleet/data/backtest-search-split-state.json\`. Recorded fact: \`screen_score_weights_${pilot}\`.`,
  ].join('\n');

  fs.writeFileSync(notePath, body, 'utf8');
  markPublished(ledgerId, notePath);
  return { written: true, path: notePath };
}

// One note per bi-daily Claude audit (added 2026-09-14, ARCHITECTURE.md
// section 14) -- Claude's only role in the continuous Codex backtest
// track: reviewing accumulated Codex findings twice a day, not backtesting
// per symbol itself. Same "read the real completed task, never fabricate"
// discipline as publishWeeklyBacktestNote().
