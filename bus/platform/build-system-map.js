// build-system-map.js -- generates docs/SYSTEM-MAP.md and bus/lib/locations.json from bus/components.json, each script's header
// comment and the real relative-require graph, so the map cannot drift from the code (tests regenerate and compare).
// Usage: node bus/platform/build-system-map.js --write

const fs = require('fs');
const path = require('path');

const BUS = path.resolve(__dirname, '..');
const REPO = path.resolve(BUS, '..');

function purposeOf(text) {
  const c = [];
  for (const l of text.split('\n').filter((x) => !x.startsWith('#!'))) {
    if (/^\s*\/\//.test(l)) c.push(l.replace(/^\s*\/\/+\s?/, '').trim()); else if (c.length) break; else if (l.trim() === '') continue; else break;
  }
  const t = c.join(' ').replace(/\s+/g, ' ').replace(/^[\w.\-]+\.js\s*[-–—:]+\s*/i, '').replace(/^Round \d+[a-z]?\s*[.:]?\s*/i, '').trim();
  const m = /^(.{30,150}?[.!?])(\s|$)/.exec(t);
  const cut = m ? m[1] : (t.length > 150 ? `${t.slice(0, 150).replace(/\s+\S*$/, '')}...` : t);
  return (cut || '(no header comment)').replace(/\|/g, '/');
}

// Reads the registry and the real files; resolves every relative require to a registered file (edges) and flags any
// require that goes through the bus/scripts compat symlinks (real code must never do that).
function scan() {
  const reg = JSON.parse(fs.readFileSync(path.join(BUS, 'components.json'), 'utf8'));
  const files = Object.keys(reg.components).sort();
  const abs = Object.fromEntries(files.map((f) => [f, path.join(BUS, reg.components[f].domain, f)]));
  const byAbs = new Map(files.map((f) => [abs[f], f]));
  const src = {};
  for (const f of files) src[f] = fs.existsSync(abs[f]) ? fs.readFileSync(abs[f], 'utf8') : null;
  const edges = [], viaScripts = [];
  for (const f of files) {
    if (src[f] === null) continue;
    for (const m of src[f].matchAll(/require\(\s*['"](\.{1,2}\/[^'"]+)['"]\s*\)/g)) {
      const t = path.resolve(path.dirname(abs[f]), m[1]);
      if (t.startsWith(path.join(BUS, 'scripts') + path.sep)) viaScripts.push([f, m[1]]);
      const hit = [t, `${t}.js`].map((c) => byAbs.get(c)).find(Boolean);
      if (hit) edges.push([f, hit]);
    }
  }
  return { reg, files, abs, src, edges, viaScripts };
}

function locations(reg) {
  return Object.fromEntries(Object.keys(reg.components).sort().map((f) => [f, `${reg.components[f].domain}/${f}`]));
}

function render() {
  const { reg, files, src, edges } = scan();
  const usedBy = (f) => new Set(edges.filter(([, t]) => t === f).map(([s]) => s)).size;
  const out = [];
  out.push('# System map (GENERATED -- do not edit by hand)', '', 'Generated by `node bus/platform/build-system-map.js --write` from `bus/components.json`, script header comments and the real `require` graph.', 'A test fails if this file is stale. For decisions and history see `docs/DECISIONS.md`; for what is scheduled see `bus/deploy/schedules.json` (check with `node bus/platform/check-schedules.js`).', 'Code lives in `bus/<domain>/<file>.js` (see the tables). `bus/scripts/` holds only compatibility symlinks for things outside the repo that still name the old paths (units, cron, the running daemon, allow rules); the list is `compatSymlinks` in `bus/components.json`.', '');
  out.push('## Domains', '', '| Domain | Meaning | Files | Live | Paused | Manual | Library | Legacy |', '|---|---|---|---|---|---|---|---|');
  for (const [d, meaning] of Object.entries(reg.domains)) {
    const fs_ = files.filter((f) => reg.components[f].domain === d); const n = (s) => fs_.filter((f) => reg.components[f].status === s).length;
    out.push(`| ${d} | ${meaning} | ${fs_.length} | ${n('live')} | ${n('paused')} | ${n('manual')} | ${n('library')} | ${n('legacy')} |`);
  }
  out.push('', '**Dependency rules** (enforced by `bus/tests/survive/architecture.test.js`): ' + Object.entries(reg.allowedDependencies).map(([d, a]) => `${d} -> ${a.join(', ')}`).join('; ') + '.', '');
  out.push('**Documented exceptions:** ' + reg.allowedExceptions.map(([a, b, why]) => `${a} -> ${b} (${why})`).join('; ') + '.', '');
  out.push('**Statuses:** ' + Object.entries(reg.statuses).map(([s, m]) => `${s} = ${m}`).join('; ') + '.', '');
  for (const d of Object.keys(reg.domains)) {
    out.push(`## ${d} (bus/${d}/)`, '', '| File | Status | Used by | Purpose (from file header) |', '|---|---|---|---|');
    for (const f of files.filter((x) => reg.components[x].domain === d)) {
      const c = reg.components[f];
      out.push(`| ${f.replace('.js', '')} | ${c.status} | ${usedBy(f)} | ${purposeOf(src[f] || '')}${c.note ? ` **Note:** ${c.note}` : ''} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

module.exports = { render, purposeOf, scan, locations };

if (require.main === module) {
  if (process.argv.includes('--write')) {
    const doc = render();
    fs.mkdirSync(path.join(REPO, 'docs'), { recursive: true });
    fs.writeFileSync(path.join(REPO, 'docs', 'SYSTEM-MAP.md'), doc + '\n');
    fs.writeFileSync(path.join(BUS, 'lib', 'locations.json'), JSON.stringify(locations(scan().reg), null, 1) + '\n');
    console.log(`wrote docs/SYSTEM-MAP.md (${doc.split('\n').length} lines) and bus/lib/locations.json`);
  } else console.log(render());
}
